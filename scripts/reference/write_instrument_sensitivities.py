def bins(energy):
    """Energy bins of which ``energy`` are the centers (log): edges at the geometric means"""
    log = np.log10(energy)
    edges = np.concatenate([[1.5 * log[0] - 0.5 * log[1]], (log[1:] + log[:-1]) / 2, [1.5 * log[-1] - 0.5 * log[-2]]])
    return 10**edges


def main(output):
    for name, (reference, unit, points) in SENSITIVITIES.items():
        energy, sensitivity = np.array(points).T
        energy = (energy * unit).to_value(u.TeV)
        sensitivity = (sensitivity * u.Unit("erg cm-2 s-1")).to_value("TeV cm-2 s-1")
        write_reference_directory(Path(output) / name, reference, reco_energy_bins=bins(energy), sensitivity=sensitivity,
                                  comments={"sensitivity": "reconstructed energy"})
        print(Path(output) / name)


if __name__ == "__main__":
    main(sys.argv[1])
